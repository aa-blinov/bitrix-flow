import { chromium } from 'playwright';
const BASE = 'http://127.0.0.1:3199';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
await page.goto(BASE + '/login');
await page.getByLabel(/логин/i).fill('tester');
await page.getByLabel(/пароль/i).fill('tester-password');
await page.waitForURL((u) => !u.pathname.includes('login'), { timeout: 15000 }).catch(() => {});
await page.goto(BASE + '/project-status');
await page.waitForTimeout(2000);
const rows = await page.locator('table tbody tr').count().catch(() => 0);
const bar = await page.getByRole('button', { name: /Только последние/i }).count();
const proj = await page.getByLabel('Проект').count();
const client = await page.getByLabel('Клиент', { exact: true }).count();
console.log(JSON.stringify({ rows, bar, proj, client }));
await page.screenshot({ path: 'scratch-ps.png' });
await browser.close();
